"""Synthetic navigation fixtures only; prepare NEW_DIR / check RESULTS_DIR.

Acceptance limits are fixed diagnostic limits, not physical accuracy claims or fits.
The 0.0005 mm face limit is 5% of the 0.01 mm layer; exact crossing sequence
is mandatory even where the endpoint allowance is larger. The 0.005 mm constant
field allowance covers accumulated navigation intersection and integration error;
affine allowances additionally cover float/texture interpolation (25 mm grid cells,
1/256 texture fractions). Refinement metrics are never required to be monotone.
Root exclusion uses unit speed and a global curvature bound; unresolved tangencies
fail preparation. Affine references must agree at two independent DOP853 tolerances.
Public momentum is fixed by construction and is checked only as record accounting.
No transport execution or successful runtime output is generated by this module.

fixtures.json links request, expected and result filenames. An optional
run-manifest.json accepts the native m2fs-navigation-run-v1 runner schema (runs,
fixture_sha256, sanitizer), or cases containing id, request, result, returncode,
backend, sanitizer_clean and guard stderr (a saved filename). Native manifests
require both separately executed guard backends and verify saved file hashes.
Guard cases require process failure, no result, no timeout and the specific marker.
Executable provenance remains the runner responsibility; no manifest means no
process/sanitizer claim, and cannot validate a suite containing a guard case.
"""

