def require(condition, message):
    if not condition:
        raise ValueError(message)


def canonical(data):
    return json.dumps(data, sort_keys=True, separators=(",", ":"), allow_nan=False)


def digest(data):
    return hashlib.sha256(canonical(data).encode()).hexdigest()


def number(value, label):
    require(type(value) in (float, int) and math.isfinite(value), label + ": expected finite number")
    return float(value)


def integer(value, label, minimum=0):
    require(type(value) is int and value >= minimum, label + ": invalid integer")
    return value


def array(value, shape, label):
    raw = np.asarray(value)
    require(raw.shape == shape and raw.dtype.kind in "fiu", label + ": invalid array")
    result = raw.astype(float)
    require(np.isfinite(result).all(), label + ": nonfinite array")
    return result


def validate_request(request):
    require(isinstance(request, dict) and set(request) == {"format", "map_file", "geometry_file", "max_records", "tracks"}, "request keys")
    require(request["format"] == REQUEST_FORMAT, "request format")
    for key in ("map_file", "geometry_file"):
        require(isinstance(request[key], str) and Path(request[key]).name == request[key] and request[key] not in ("", ".", ".."), key + ": basename required")
    capacity = integer(request["max_records"], "max_records", 1)
    require(capacity <= 8192, "per-track record limit")
    tracks = request["tracks"]
    require(isinstance(tracks, list) and 1 <= len(tracks) <= 128 and capacity * len(tracks) <= 262144, "request record/path limits")
    ids = []
    required = {"id", "position_mm", "direction", "momentum_mev_c", "charge_e", "length_mm", "max_step_mm", "minimum_step_mm", "delta_chord_mm", "delta_intersection_mm", "epsilon_rel_max"}
    for track in tracks:
        require(isinstance(track, dict) and required <= set(track) <= required | {"max_substeps", "max_nsteps"}, "track keys")
        require(isinstance(track["id"], str) and track["id"], "track id")
        ids.append(track["id"])
        require(np.max(np.abs(array(track["position_mm"], (3,), "position"))) <= 1e6, "position diagnostic bounds")
        direction = array(track["direction"], (3,), "direction")
        require(abs(np.linalg.norm(direction) - 1) <= 1e-12, "initial unit direction")
        require(type(track["charge_e"]) is int and track["charge_e"] in (-1, 0, 1), "charge")
        for key in ("momentum_mev_c", "length_mm", "max_step_mm", "minimum_step_mm", "delta_chord_mm", "delta_intersection_mm", "epsilon_rel_max"):
            require(number(track[key], key) > 0, key + ": positive required")
        require(track["delta_intersection_mm"] > track["minimum_step_mm"] and 1e-12 <= track["epsilon_rel_max"] <= 0.01, "driver tolerances")
        require(0.1 <= track["momentum_mev_c"] <= 1000 and 1e-4 <= track["length_mm"] <= 10000
                and 1e-4 <= track["max_step_mm"] <= 1000, "kinematic diagnostic bounds")
        for key, default in (("max_substeps", 1000), ("max_nsteps", 100)):
            require(integer(track.get(key, default), key, 1) <= 30000, "driver iteration limit")
    require(len(set(ids)) == len(ids), "duplicate track id")
    return request


def helix(position, direction, momentum, charge, paths, field):
    """Vectorized exact constant-field solution of du/ds = k q (u cross B)/p."""
    s = np.atleast_1d(np.asarray(paths, dtype=float))
    require(s.ndim == 1 and np.isfinite(s).all() and np.all(s >= 0), "helix paths")
    x = array(position, (3,), "helix position")
    u = array(direction, (3,), "helix direction")
    b = array(field, (3,), "helix field")
    require(abs(np.linalg.norm(u) - 1) < 1e-12 and number(momentum, "helix momentum") > 0 and charge in (-1, 0, 1), "helix initial state")
    bmag = np.linalg.norm(b)
    axis = b / bmag if bmag else np.zeros(3)
    parallel = np.dot(u, axis) * axis
    transverse = u - parallel
    rotated = np.cross(transverse, axis)
    theta = KAPPA * charge * bmag * s / momentum
    displacement = s[:, None] * (parallel + np.sinc(theta / np.pi)[:, None] * transverse + (0.5 * theta * np.sinc(theta / (2 * np.pi)) ** 2)[:, None] * rotated)
    directions = parallel + np.cos(theta)[:, None] * transverse + np.sin(theta)[:, None] * rotated
    return x + displacement, directions


class Reference:
    """Dense independent reference; numerical references are checked at every queried path."""

    def __init__(self, track, model):
        self.track = track
        self.b0 = array(model["b0_tesla"], (3,), "b0")
        self.gradient = array(model["gradient_tesla_per_mm"], (3, 3), "gradient")
        require(abs(np.trace(self.gradient)) < 1e-18, "reference field not divergence free")
        self.length = track["length_mm"]
        x0 = np.asarray(track["position_mm"])
        bound = np.linalg.norm(np.abs(self.b0) + (np.abs(x0) + self.length) @ np.abs(self.gradient))
        self.curvature = KAPPA * abs(track["charge_e"]) * bound / track["momentum_mev_c"]
        self.solutions = []
        if np.any(self.gradient):
            initial = np.r_[x0, track["direction"]]

            def rhs(s, state):
                u = state[3:]
                return np.r_[u, KAPPA * track["charge_e"] / track["momentum_mev_c"] * np.cross(u, state[:3] @ self.gradient + self.b0)]

            for tolerance in (2e-12, 3e-14):
                solution = solve_ivp(rhs, (0, self.length), initial, method="DOP853", dense_output=True, rtol=tolerance, atol=tolerance * 0.01, max_step=min(self.length, 0.1 / max(self.curvature, 1e-30)))
                require(solution.success and solution.t[-1] == self.length, "DOP853 did not complete")
                self.solutions.append(solution.sol)
            self(np.linspace(0, self.length, 257))

    def __call__(self, paths):
        s = np.atleast_1d(np.asarray(paths, dtype=float))
        require(s.ndim == 1 and np.isfinite(s).all() and np.all(s >= 0) and np.all(s <= self.length + 1e-8), "reference path outside interval")
        s = np.minimum(s, self.length)
        if not self.solutions:
            t = self.track
            return helix(t["position_mm"], t["direction"], t["momentum_mev_c"], t["charge_e"], s, self.b0)
        loose, tight = (solution(s).T for solution in self.solutions)
        require(np.max(np.linalg.norm(loose[:, :3] - tight[:, :3], axis=1), initial=0) < 2e-8 and np.max(np.linalg.norm(loose[:, 3:] - tight[:, 3:], axis=1), initial=0) < 2e-10, "DOP853 reference disagreement")
        require(np.max(np.abs(np.linalg.norm(tight[:, 3:], axis=1) - 1), initial=0) < 2e-10, "DOP853 unit-speed disagreement")
        return tight[:, :3], tight[:, 3:]


def plane_roots(reference, axis, coordinate):
    """Certified interval exclusion/monotonicity, never a fixed-grid sign-change scan."""
    left = np.array([0.0])
    right = np.array([reference.length])
    roots = []
    for depth in range(50):
        if not len(left):
            break
        middle = (left + right) / 2
        half = (right - left) / 2
        x, u = reference(middle)
        f = x[:, axis] - coordinate
        excluded = np.abs(f) > half * (1 + 1e-9) + 4e-8
        monotone = np.abs(u[:, axis]) > reference.curvature * half * (1 + 1e-9) + 4e-10
        candidates = ~excluded & monotone
        if np.any(candidates):
            a, b = left[candidates], right[candidates]
            fa = reference(a)[0][:, axis] - coordinate
            fb = reference(b)[0][:, axis] - coordinate
            for lo, hi in zip(a[fa * fb <= 0], b[fa * fb <= 0]):
                roots.append(brentq(lambda s: reference([s])[0][0, axis] - coordinate, lo, hi, xtol=1e-11, rtol=1e-14))
        unresolved = ~excluded & ~monotone
        require(not np.any(unresolved & (half < 1e-7)), "unresolved near/exact tangency: root isolation refused")
        a, b, m = left[unresolved], right[unresolved], middle[unresolved]
        left, right = np.r_[a, m], np.r_[m, b]
        require(len(left) < 100000, "root isolation resource cap")
    require(not len(left), "root isolation depth cap")
    roots = np.sort(roots)
    if len(roots):
        roots = roots[np.r_[True, np.diff(roots) > 1e-7]]
    return roots


def volume_at(points, boxes=BOXES):
    p = np.asarray(points, dtype=float)
    require(p.ndim == 2 and p.shape[1] == 3, "volume points")
    labels = np.full(len(p), "outside", dtype=object)
    for box in boxes:
        inside = np.all((p > box["lower_mm"]) & (p < box["upper_mm"]), axis=1)
        labels[inside] = box["name"]
    return labels


def expected_track(track, model, boxes=BOXES):
    reference = Reference(track, model)
    candidates = []
    for box in boxes:
        for axis in range(3):
            others = [i for i in range(3) if i != axis]
            for side, key in ((-1, "lower_mm"), (1, "upper_mm")):
                roots = plane_roots(reference, axis, box[key][axis])
                if not len(roots):
                    continue
                x, u = reference(roots)
                inside = np.all((x[:, others] > np.asarray(box["lower_mm"])[others] + 1e-7) & (x[:, others] < np.asarray(box["upper_mm"])[others] - 1e-7), axis=1)
                on_edge = np.all((x[:, others] >= np.asarray(box["lower_mm"])[others] - 1e-7) & (x[:, others] <= np.asarray(box["upper_mm"])[others] + 1e-7), axis=1) & ~inside
                require(not np.any(on_edge), "ambiguous box edge/corner")
                for s, position, direction in zip(roots[inside], x[inside], u[inside]):
                    require(1e-6 < s < track["length_mm"] - 1e-6, "boundary at initial/final path is ambiguous")
                    normal = np.zeros(3)
                    normal[axis] = side
                    candidates.append({"path_mm": float(s), "position_mm": position.tolist(), "direction": direction.tolist(), "normal": normal.tolist(), "face_coordinate_mm": box[key][axis], "face_axis": axis})
    candidates.sort(key=lambda crossing: crossing["path_mm"])
    paths = np.array([crossing["path_mm"] for crossing in candidates])
    require(not len(paths) or np.min(np.diff(np.r_[0, paths, track["length_mm"]])) > 1e-6, "unresolved coincident crossings")
    crossings = []
    final_path = track["length_mm"]
    status = 0
    for i, crossing in enumerate(candidates):
        previous = candidates[i - 1]["path_mm"] if i else 0
        following = candidates[i + 1]["path_mm"] if i + 1 < len(candidates) else track["length_mm"]
        labels = volume_at(reference([(previous + crossing["path_mm"]) / 2, (following + crossing["path_mm"]) / 2])[0], boxes)
        require(labels[0] != labels[1], "face root did not change volume")
        crossing.update(volume_before=str(labels[0]), volume_after=str(labels[1]))
        crossings.append(crossing)
        if labels[1] == "outside":
            final_path, status = crossing["path_mm"], 1
            break
    x, u = reference([final_path])
    initial_volume = str(volume_at(reference([0])[0], boxes)[0])
    final_volume = crossings[-1]["volume_after"] if crossings else initial_volume
    return {"id": track["id"], "status": status, "initial_volume": initial_volume, "crossings": crossings, "path_mm": final_path, "final": {"position_mm": x[0].tolist(), "direction": u[0].tolist(), "volume": final_volume}}


def make_map(model):
    axes = [{"min_mm": -250.0, "max_mm": 250.0, "num": 21} for _ in range(3)]
    grid = np.stack(np.meshgrid(*(np.linspace(a["min_mm"], a["max_mm"], a["num"]) for a in axes), indexing="ij"), axis=-1)
    values = grid @ np.asarray(model["gradient_tesla_per_mm"]) + model["b0_tesla"]
    return {"format": "m2fs-cartmap-v1", "length_unit": "mm", "field_unit": "tesla", "coordinates": "gdml-world", "outside_policy": "world-contained", "order": "xyz-component", "axes": axes, "field": values.ravel().tolist()}


def gdml(boxes=BOXES):
    solids, volumes, placements = [], [], []
    for box in boxes:
        name = box["name"]
        size = np.asarray(box["upper_mm"]) - box["lower_mm"]
        center = (np.asarray(box["upper_mm"]) + box["lower_mm"]) / 2
        solids.append(f'<box name="{name}_solid" x="{size[0]:.17g}" y="{size[1]:.17g}" z="{size[2]:.17g}" lunit="mm"/>')
        if box is not boxes[0]:
            volumes.append(f'<volume name="{name}"><materialref ref="nav_vacuum"/><solidref ref="{name}_solid"/></volume>')
            placements.append(f'<physvol name="{name}_pv"><volumeref ref="{name}"/><position name="{name}_pos" x="{center[0]:.17g}" y="{center[1]:.17g}" z="{center[2]:.17g}" unit="mm"/></physvol>')
    world = boxes[0]["name"]
    return '<?xml version="1.0"?>\n<gdml><define/><materials><material name="nav_vacuum" Z="1" state="gas"><D value="1e-25" unit="g/cm3"/><atom value="1.00794" unit="g/mole"/></material></materials><solids>' + ''.join(solids) + '</solids><structure>' + ''.join(volumes) + f'<volume name="{world}"><materialref ref="nav_vacuum"/><solidref ref="{world}_solid"/>' + ''.join(placements) + f'</volume></structure><setup name="Default" version="1.0"><world ref="{world}"/></setup></gdml>\n'


def track_config(name, **changes):
    track = {"id": name, "position_mm": [-10.0, 0.0, 0.0], "direction": [1.0, 0.0, 0.0], "momentum_mev_c": 5.0, "charge_e": 1, "length_mm": 25.0, "max_step_mm": 4.0, "minimum_step_mm": 1e-7, "delta_chord_mm": 0.001, "delta_intersection_mm": 1e-5, "epsilon_rel_max": 1e-7, "max_substeps": 1000, "max_nsteps": 100}
    track.update(changes)
    return track


def fixture_definitions():
    zero = {"b0_tesla": [0.0, 0.0, 0.0], "gradient_tesla_per_mm": np.zeros((3, 3)).tolist()}
    constant = dict(zero, b0_tesla=[0.0, 0.0, 1.0])
    affine = {"b0_tesla": [0.1, -0.05, 1.0], "gradient_tesla_per_mm": GRADIENT.tolist()}
    yield "zero", zero, [track_config(f"zero_q{q}", charge_e=q) for q in (-1, 0, 1)], "positive", 2048
    variants = [("base", {}), ("chord", {"delta_chord_mm": 0.0002}), ("intersection", {"delta_intersection_mm": 2e-6}), ("epsilon", {"epsilon_rel_max": 1e-9}), ("cap", {"max_step_mm": 1.0})]
    repeated = [track_config(f"repeat_q{q}_{name}", position_mm=[-5.0, 0.0, 0.0], length_mm=230.0, charge_e=q, **changes) for q in (-1, 1) for name, changes in variants]
    yield "constant", constant, repeated, "positive", 2048
    radius = 5.0 / KAPPA
    tangent = [track_config(f"tangent_{kind}_q{q}", position_mm=[-radius + peak, 0.0, 0.0], charge_e=q, length_mm=math.pi * radius, max_step_mm=1.0, delta_chord_mm=1e-4, delta_intersection_mm=1e-6, epsilon_rel_max=1e-9) for q in (-1, 1) for kind, peak in (("hit", -0.03), ("miss", -0.07))]
    yield "tangent", constant, tangent, "positive", 2048
    yield "affine", affine, [track_config(f"affine_q{q}", momentum_mev_c=15.0, charge_e=q, length_mm=80.0) for q in (-1, 0, 1)], "positive", 2048
    yield "world_exit", zero, [track_config("world_exit", position_mm=[190.0, 190.0, 0.0], length_mm=20.0)], "positive", 2048
    yield "outer_limit", constant, [track_config("outer_limit", position_mm=[-50.0, 0.0, 0.0], length_mm=100.0, max_step_mm=4.0, delta_chord_mm=1e-4, max_substeps=1)], "outer_limit", 2048
    yield "record_limit", zero, [track_config("record_limit", max_step_mm=1.0)], "record_limit", 1
    yield "guard", constant, [track_config("guard", position_mm=[199.9, 0.0, 0.0], direction=[0.0, 1.0, 0.0], momentum_mev_c=0.2, charge_e=-1, length_mm=400.0, max_step_mm=400.0)], "guard", 2048


def prepare(directory, case_ids=None):
    directory = Path(directory)
    definitions = list(fixture_definitions())
    require(case_ids is None or case_ids and set(case_ids) <= {row[0] for row in definitions}, "unknown/empty selected cases")
    require(not directory.exists(), "prepare requires a NEW directory")
    directory.mkdir(parents=True)
    index = {"format": INDEX_FORMAT, "cases": [], "selected_fixture_set": case_ids is not None}
    for name, model, tracks, kind, capacity in definitions:
        if case_ids is not None and name not in case_ids:
            continue
        request = validate_request({"format": REQUEST_FORMAT, "map_file": name + ".map.json", "geometry_file": name + ".gdml", "max_records": capacity, "tracks": tracks})
        expected = {"format": EXPECTED_FORMAT, "kind": kind, "request_sha256": digest(request), "model": model, "boxes": BOXES, "budgets": AFFINE_BUDGETS if name == "affine" else BUDGETS, "tracks": []}
        if kind == "positive":
            expected["tracks"] = [expected_track(track, model) for track in tracks]
        elif kind != "guard":
            expected["tracks"] = [{"id": track["id"], "status": 2 if kind == "outer_limit" else 3, "initial_volume": str(volume_at(np.asarray([track["position_mm"]]))[0])} for track in tracks]
        else:
            expected["process_marker"] = "M2FS_NAV_MAP_GUARD"
        case = {"id": name, "kind": kind, "request": name + ".request.json", "expected": name + ".expected.json", "result": name + ".result.json"}
        for filename, data in ((case["request"], request), (case["expected"], expected), (request["map_file"], make_map(model))):
            (directory / filename).write_text(json.dumps(data, indent=2, allow_nan=False) + "\n")
        (directory / request["geometry_file"]).write_text(gdml())
        index["cases"].append(case)
    (directory / "fixtures.json").write_text(json.dumps(index, indent=2) + "\n")
    return index


def _label_table(metadata, key):
    entries = metadata.get(key)
    require(isinstance(entries, list) and entries, key + ": missing metadata")
    result = {}
    for entry in entries:
        i = integer(entry.get("id"), key + " id")
        require(i not in result and isinstance(entry.get("name"), str) and entry["name"] and isinstance(entry.get("ext"), str), key + ": malformed/duplicate label")
        require(entry["name"] not in result.values(), key + ": ambiguous repeated synthetic name")
        result[i] = entry["name"]
    return result


def _states(states, logical, instances):
    require(all(isinstance(state, dict) and set(state) == {"position_mm", "direction", "volume_id", "instance_id", "boundary", "outside"} for state in states), "state keys")
    positions = array([state["position_mm"] for state in states], (len(states), 3), "state positions")
    directions = array([state["direction"] for state in states], (len(states), 3), "state directions")
    require(np.all(np.abs(np.linalg.norm(directions, axis=1) - 1) <= 1e-10), "state unit directions")
    names = []
    for state in states:
        require(type(state["boundary"]) is bool and type(state["outside"]) is bool and type(state["volume_id"]) is int and type(state["instance_id"]) is int, "state flags/ids")
        if state["outside"]:
            require(state["volume_id"] == -1 and state["instance_id"] == -1, "outside ids")
            names.append("outside")
        else:
            require(state["volume_id"] in logical and state["instance_id"] in instances, "unmapped geometry id")
            name = logical[state["volume_id"]]
            names.append(name)
    return positions, directions, np.asarray(names)


def check_result(request, result, expected):
    """Audit real saved records only; returns raw residuals without refinement rankings."""
    validate_request(request)
    require(expected.get("format") == EXPECTED_FORMAT and expected.get("request_sha256") == digest(request), "expectation/request mismatch")
    kind = expected.get("kind")
    require(kind in ("positive", "outer_limit", "record_limit"), "guard requires a process failure, not a transport result")
    require(isinstance(result, dict) and result.get("format") == RESULT_FORMAT and canonical(result.get("input")) == canonical(request), "result format/exact input mismatch")
    backend = result.get("backend")
    require(backend in ("host", "device", "both"), "result backend")
    require(result.get("units") == {"length": "mm", "time": "ns", "momentum": "MeV/c"}, "result units")
    active = ["host", "device"] if backend == "both" else [backend]
    require(isinstance(result.get("tracks"), dict) and set(result["tracks"]) == set(active), "backend arrays")
    canonical(result)
    if "device" in active:
        device = result.get("device", {})
        require(isinstance(device, dict) and device.get("synchronized") is True and isinstance(device.get("name"), str) and device["name"] and device.get("capability") not in (None, "", []), "missing synchronized device evidence")
    metadata = result.get("metadata", {})
    if kind == "positive":
        require(metadata.get("geometry_loader") == "Geant4/G4VG" and metadata.get("interactions_enabled") is False
                and metadata.get("celeritas_version") == "0.6.3"
                and metadata.get("momentum_magnitude_is_transport_constraint") is True, "navigation scope/version metadata")
        require(result.get("device", {}).get("capability") == 80 and "A100" in result["device"].get("name", ""), "A100 execution required")
    logical = _label_table(metadata, "logical_volumes")
    instances = _label_table(metadata, "volume_instances")
    budgets = expected["budgets"]
    require(budgets == (AFFINE_BUDGETS if np.any(expected["model"]["gradient_tesla_per_mm"]) else BUDGETS), "unrecognized/fitted acceptance budgets")
    require(expected.get("boxes") == BOXES, "unrecognized oracle geometry")
    require(set(logical.values()) <= {box["name"] for box in BOXES}, "unexpected logical volume label")
    instance_pairs = {(box["name"], box["name"]) for box in BOXES} | {(box["name"], box["name"] + "_pv") for box in BOXES[1:]}
    require(len(expected["tracks"]) == len(request["tracks"]), "expected track count")
    metrics = []
    for backend_name in active:
        outputs = result["tracks"][backend_name]
        require(isinstance(outputs, list) and len(outputs) == len(request["tracks"]), "result track count")
        for track, output, oracle in zip(request["tracks"], outputs, expected["tracks"]):
            require(output.get("id") == track["id"] == oracle["id"], "track id/order")
            require(oracle["status"] in ((0, 1) if kind == "positive" else (2,) if kind == "outer_limit" else (3,)), "expectation status/kind mismatch")
            require(integer(output.get("status"), "status") == oracle["status"], "unexpected terminal status")
            require(type(output.get("completed_tag")) is int and output["completed_tag"] == TAG, "track incomplete")
            steps = output.get("steps")
            n = integer(output.get("count"), "count", 1)
            require(isinstance(steps, list) and len(steps) == n <= request["max_records"], "record count/capacity")
            require(all(step.get("completed_tag") == TAG and type(step.get("completed_tag")) is int for step in steps), "step incomplete")
            required_steps = {"before", "arrival", "after", "requested_mm", "distance_mm", "cumulative_path_mm", "momentum_mev_c", "time_ns", "field_evaluations", "substep_calls", "boundary", "looping", "geometry_failed", "completed_tag"}
            require(all(set(step) == required_steps for step in steps), "step keys")
            before = [step["before"] for step in steps]
            arrival = [step["arrival"] for step in steps]
            after = [step["after"] for step in steps]
            bx, bu, bn = _states(before, logical, instances)
            ax, au, an = _states(arrival, logical, instances)
            cx, cu, cn = _states(after, logical, instances)
            _states([output["final"]], logical, instances)
            require(all(state["outside"] or logical[state["volume_id"]] == "nav_world" or (logical[state["volume_id"]], instances[state["instance_id"]]) in instance_pairs for state in before + arrival + after), "placed/logical volume label mismatch")
            require(all(before[i] == after[i - 1] for i in range(1, n)) and output["final"] == after[-1], "hidden inter-call state change/final mismatch")
            require(np.max(np.abs(bx[0] - track["position_mm"])) <= 1e-11 and np.max(np.abs(bu[0] - track["direction"])) <= 1e-14 and bn[0] == oracle["initial_volume"] and before[0]["outside"] is False and before[0]["boundary"] is False, "initial state")
            require(np.array_equal(ax, cx) and np.array_equal(au, cu), "hidden boundary position/direction push")
            flags = {}
            for key in ("boundary", "looping", "geometry_failed"):
                require(all(type(step[key]) is bool for step in steps), "record flag type")
                flags[key] = np.asarray([step[key] for step in steps])
            require(not flags["geometry_failed"].any(), "geometry failure")
            boundary = flags["boundary"]
            require(np.array_equal(boundary, [state["boundary"] for state in arrival]), "arrival/boundary mismatch")
            require(np.all(bn == an) and all(a["volume_id"] == b["volume_id"] and a["instance_id"] == b["instance_id"] and not a["outside"] for a, b in zip(arrival, before)), "volume changed before explicit crossing")
            require(all(a == c for a, c, hit in zip(arrival, after, boundary) if not hit), "nonboundary geometry change")
            require(np.all(an[boundary] != cn[boundary]) and all(a["instance_id"] != c["instance_id"] and c["boundary"] for a, c, hit in zip(arrival, after, boundary) if hit), "missing/invalid boundary crossing")
            columns = {key: array([number(step[key], key) for step in steps], (n,), key) for key in ("requested_mm", "distance_mm", "cumulative_path_mm", "momentum_mev_c", "time_ns")}
            distance, path = columns["distance_mm"], columns["cumulative_path_mm"]
            previous = np.r_[0, path[:-1]]
            tolerance = budgets["accounting_mm"]
            require(np.all(distance > 0) and np.all(np.diff(path) > 0) and np.all(distance <= columns["requested_mm"] * (1 + 1e-10)), "nonprogress/overstep")
            require(np.max(np.abs(path - np.cumsum(distance))) <= tolerance and abs(number(output.get("path_mm"), "track path") - path[-1]) <= tolerance, "path accounting")
            require(np.max(np.abs(columns["requested_mm"] - np.minimum(track["max_step_mm"], track["length_mm"] - previous))) <= tolerance, "requested path accounting")
            require(np.all(np.linalg.norm(ax - bx, axis=1) <= distance + budgets["position_mm"]), "endpoint chord exceeds reported path")
            require(np.all(np.abs(columns["momentum_mev_c"] / track["momentum_mev_c"] - 1) <= 1e-10), "public fixed momentum accounting")
            speed = 299.792458 * track["momentum_mev_c"] / math.hypot(track["momentum_mev_c"], 0.5109989461)
            require(np.max(np.abs(columns["time_ns"] - path / speed)) <= 1e-10 + tolerance / speed, "time accounting")
            for key in ("field_evaluations", "substep_calls"):
                values = [integer(step[key], key) for step in steps]
                require(integer(output.get(key), key) == sum(values), "audit count mismatch: " + key)
                if kind == "positive":
                    require(all(value > 0 for value in values), "missing positive propagation audit: " + key)
            if output["field_evaluations"]:
                require(number(output.get("min_margin_mm"), "min_margin_mm") >= 0, "map guard margin")
            else:
                require(output.get("min_margin_mm") is None, "unused field margin must be null")
            require(integer(output.get("crossings"), "crossings") == int(boundary.sum()), "crossing count")
            require(not np.any(flags["looping"][:-1]) and not any(state["outside"] for state in after[:-1]), "records after terminal condition")
            if kind == "outer_limit":
                require(n == 1 and flags["looping"][-1] and path[-1] < track["length_mm"] and output["substep_calls"] >= 1, "outer-limit negative did not exhaust")
            elif kind == "record_limit":
                require(n == request["max_records"] == 1 and path[-1] < track["length_mm"] and not flags["looping"].any() and not after[-1]["outside"], "record-cap negative did not exhaust")
            else:
                require(not flags["looping"].any(), "positive looping")
                require(after[-1]["outside"] == (oracle["status"] == 1), "terminal outside status")
                if oracle["status"] == 0:
                    require(abs(path[-1] - track["length_mm"]) <= tolerance, "incomplete positive path")
            reference = Reference(track, expected["model"])
            rx, ru = reference(path)
            position_errors = np.linalg.norm(ax - rx, axis=1)
            direction_errors = np.linalg.norm(au - ru, axis=1)
            require(np.max(position_errors) <= budgets["position_mm"] and np.max(direction_errors) <= budgets["direction"], "independent path/endpoint residual")
            crossing_path = crossing_position = face_error = 0.0
            expected_crossings = oracle.get("crossings")
            if kind != "positive":
                expected_crossings = expected_track(track, expected["model"])["crossings"]
                expected_crossings = [c for c in expected_crossings if c["path_mm"] <= path[-1] + tolerance]
            hits = np.flatnonzero(boundary)
            require(len(hits) == len(expected_crossings), "missing/extra crossings")
            if len(hits):
                ep = np.array([c["path_mm"] for c in expected_crossings])
                ex = np.array([c["position_mm"] for c in expected_crossings])
                eu = np.array([c["direction"] for c in expected_crossings])
                normal = np.array([c["normal"] for c in expected_crossings])
                require(np.array_equal(bn[hits], [c["volume_before"] for c in expected_crossings]) and np.array_equal(cn[hits], [c["volume_after"] for c in expected_crossings]), "crossing sequence")
                crossing_path = float(np.max(np.abs(path[hits] - ep)))
                crossing_position = float(np.max(np.linalg.norm(ax[hits] - ex, axis=1)))
                face_error = float(np.max(np.abs(np.sum((ax[hits] - ex) * normal, axis=1))))
                require(crossing_path <= budgets["path_mm"] and crossing_position <= budgets["position_mm"] and face_error <= budgets["face_mm"], "independent crossing residual")
                require(np.max(np.linalg.norm(au[hits] - eu, axis=1)) <= budgets["direction"] and np.all(np.sum(au[hits] * normal, axis=1) * np.sum(eu * normal, axis=1) > 0), "crossing direction/analytic normal orientation")
            if kind == "positive":
                require(abs(path[-1] - oracle["path_mm"]) <= budgets["path_mm"] and cn[-1] == oracle["final"]["volume"], "final path/volume")
                require(np.linalg.norm(ax[-1] - oracle["final"]["position_mm"]) <= budgets["position_mm"] and np.linalg.norm(au[-1] - oracle["final"]["direction"]) <= budgets["direction"], "independent final state")
            metrics.append({"backend": backend_name, "id": track["id"], "kind": kind, "position_max_mm": float(np.max(position_errors)), "direction_max": float(np.max(direction_errors)), "crossing_path_max_mm": crossing_path, "crossing_position_max_mm": crossing_position, "face_max_mm": face_error, "path_mm": float(path[-1]), "field_evaluations": output["field_evaluations"], "substep_calls": output["substep_calls"]})
    return metrics


def _local(directory, filename):
    require(isinstance(filename, str) and Path(filename).name == filename and filename not in ("", ".", ".."), "manifest requires local basenames")
    path = directory / filename
    require(path.resolve().parent == directory.resolve(), "manifest symlink escape")
    return path


def check_sanitizer(directory, run):
    text_path = _local(directory, run.get("sanitizer_log"))
    require(hashlib.sha256(text_path.read_bytes()).hexdigest() == run.get("sanitizer_sha256"), "changed sanitizer log")
    text = text_path.read_text()
    errors = re.findall(r"ERROR SUMMARY: (\d+) errors?", text)
    require(run.get("sanitizer_clean") is True and bool(errors) and all(int(n) == 0 for n in errors)
            and "COMPUTE-SANITIZER" in text and "========= ERROR:" not in text, "sanitizer not clean")


def check(directory, case_ids=None):
    directory = Path(directory)
    index = json.loads((directory / "fixtures.json").read_text())
    require(index.get("format") == INDEX_FORMAT and isinstance(index.get("cases"), list) and index["cases"], "fixture index")
    all_cases = index["cases"]
    all_ids = [case["id"] for case in all_cases]
    require(len(set(all_ids)) == len(all_ids), "duplicate fixture case")
    require(case_ids is None or case_ids and set(case_ids) <= set(all_ids), "unknown/empty selected cases")
    cases = [case for case in all_cases if case_ids is None or case["id"] in case_ids]
    ids = [case["id"] for case in cases]
    manifest_path = directory / "run-manifest.json"
    runs = None
    native = False
    if manifest_path.exists():
        manifest = json.loads(manifest_path.read_text())
        native = manifest.get("format") == "m2fs-navigation-run-v1"
        if native:
            require(isinstance(manifest.get("runs"), list) and type(manifest.get("sanitizer")) is bool and isinstance(manifest.get("fixture_sha256"), dict), "native run manifest")
            required_files = {"fixtures.json"}
            for case in cases:
                required_files.update((case["request"], case["expected"]))
                request = json.loads(_local(directory, case["request"]).read_text())
                required_files.update((request["map_file"], request["geometry_file"]))
            require(required_files <= manifest["fixture_sha256"].keys(), "missing fixture hashes")
            for name, sha in manifest["fixture_sha256"].items():
                require(hashlib.sha256(_local(directory, name).read_bytes()).hexdigest() == sha, "changed fixture: " + name)
            runs = {case["id"]: [] for case in cases}
            by_request = {case["request"]: case for case in all_cases}
            for run in manifest["runs"]:
                require(run.get("request") in by_request, "unknown run request")
                case = by_request[run["request"]]
                if case["id"] not in ids:
                    continue
                require(run.get("accepted_process") is True and run.get("negative_guard") == (case["kind"] == "guard"), "runner rejected process")
                log_name = run["name"] + ".log"
                require(hashlib.sha256(_local(directory, log_name).read_bytes()).hexdigest() == run["log_sha256"], "changed run log")
                if case["kind"] != "guard":
                    require(run.get("result_sha256") == hashlib.sha256(_local(directory, run["result"]).read_bytes()).hexdigest(), "changed result")
                    if manifest["sanitizer"]:
                        check_sanitizer(directory, run)
                runs[case["id"]].append(dict(run, stderr=log_name))
        else:
            require(isinstance(manifest.get("cases"), list), "run manifest cases")
            runs = {case["id"]: [case] for case in manifest["cases"]}
            require(len(runs) == len(manifest["cases"]), "duplicate manifest case")
            require(set(runs) <= set(all_ids), "unknown manifest case")
            runs = {key: value for key, value in runs.items() if key in ids}
        require(set(runs) == set(ids), "manifest fixture coverage")
    metrics = []
    for case in cases:
        request = json.loads(_local(directory, case["request"]).read_text())
        expected = json.loads(_local(directory, case["expected"]).read_text())
        validate_request(request)
        require(expected.get("format") == EXPECTED_FORMAT and expected["request_sha256"] == digest(request) and expected["kind"] == case["kind"], "indexed expectation mismatch")
        case_runs = runs[case["id"]] if runs is not None else []
        if case["kind"] == "guard":
            require(case_runs and (not native or len(case_runs) == 2 and {run["backend"] for run in case_runs} == {"host", "device"}), "guard requires separate-backend process failure evidence")
            require(expected.get("process_marker") == "M2FS_NAV_MAP_GUARD", "guard marker contract")
            for run in case_runs:
                require(run.get("request") == case["request"], "guard request mismatch")
                require(run["backend"] in ("host", "device") and type(run["returncode"]) is int and run["returncode"] not in (0, 124), "guard requires separate-backend process failure evidence")
                require(not _local(directory, run["result"]).exists(), "guard emitted a transport result")
                require(expected["process_marker"] in _local(directory, run["stderr"]).read_text(), "missing map guard diagnostic")
                metrics.append({"id": case["id"], "kind": "guard", "backend": run["backend"], "returncode": run["returncode"]})
            continue
        if runs is not None:
            require(len(case_runs) == 1, "missing/duplicate positive run")
            run = case_runs[0]
            require(run["request"] == case["request"] and run["result"] == case["result"] and run["backend"] in ("host", "device", "both") and type(run["returncode"]) is int and run["returncode"] == 0, "runtime failure/schema mismatch")
            require(native or run.get("sanitizer_clean") is True, "runtime/sanitizer failure")
        result = json.loads(_local(directory, case["result"]).read_text())
        if runs is not None:
            require(result["backend"] == case_runs[0]["backend"], "manifest/result backend mismatch")
        metrics.extend(check_result(request, result, expected))
    return {"format": "m2fs-navigation-check-v1", "metrics": metrics, "process_manifest_checked": runs is not None, "sanitizer_checked": runs is not None and (not native or manifest["sanitizer"]),
            "complete_suite": case_ids is None and not index.get("selected_fixture_set", False), "checked_cases": ids,
            "scope": "selected cases only; not a suite pass" if case_ids is not None or index.get("selected_fixture_set", False) else "full suite"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("prepare", "check"))
    parser.add_argument("directory", type=Path)
    parser.add_argument("--case", action="append", dest="cases", help="Prepare/check selected cases only")
    args = parser.parse_args()
    result = prepare(args.directory, args.cases) if args.command == "prepare" else check(args.directory, args.cases)
    print(json.dumps(result, indent=2, allow_nan=False))


if __name__ == "__main__":
    main()
